#!/usr/bin/env python3
"""Print the sampling table for SPOT-CHECKS.md.

Run from anywhere:

    python3 scripts/make-sampling-table.py
    python3 scripts/make-sampling-table.py --check
    python3 scripts/make-sampling-table.py --write

With no argument, print the table. --check exits 1 when the fenced table in
SPOT-CHECKS.md differs, or when the Generated by line or its text fence is
missing or unclosed. --write replaces that fenced table and writes nothing
else. Any other argument, or both flags together, prints usage and exits 2.

The chance that a sample of n rows contains at least one of k wrong rows in
a catalog of N rows is the exact fraction 1 - C(N-k, n) / C(N, n). It is
rounded half up to one decimal place of a percent. A value below 100 that
rounds to 100.0 prints as >99.9%. Exactly 100 prints as 100.0%. Output is
LF, with no trailing spaces and no timestamps.
"""

from __future__ import annotations

import math
import sys
from decimal import Decimal, ROUND_HALF_UP
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPOT_CHECKS = ROOT / "SPOT-CHECKS.md"
MARKER = (
    "Generated by `scripts/make-sampling-table.py`; do not edit the table by hand."
)
USAGE = "Usage: python3 scripts/make-sampling-table.py [--check | --write]"

# Fixed grid: catalog rows, wrong rows, and sample rows.
CATALOG_SIZES = (200, 1000, 5000)
WRONG_COUNTS = (1, 5, 10, 25)
SAMPLE_SIZES = (15, 30, 50, 100)


class TableLocationError(Exception):
    """The sampling table fence in SPOT-CHECKS.md is missing or unclosed."""


def chance(catalog_rows: int, wrong_rows: int, sample_rows: int) -> Fraction:
    """Return 1 - C(N-k, n) / C(N, n) as an exact fraction.

    N is catalog_rows, k is wrong_rows, and n is sample_rows.
    """
    values = (catalog_rows, wrong_rows, sample_rows)
    if any(isinstance(value, bool) or not isinstance(value, int) for value in values):
        raise ValueError("N, k, and n must be integers")
    if catalog_rows < 1 or wrong_rows < 1 or sample_rows < 1:
        raise ValueError("N, k, and n must be at least 1")
    if sample_rows > catalog_rows:
        raise ValueError("n must not be greater than N")
    if wrong_rows > catalog_rows:
        raise ValueError("k must not be greater than N")
    # math.comb(a, b) is 0 when 0 <= a < b, so the chance is exactly 1
    # when fewer than n rows are not wrong.
    return 1 - Fraction(
        math.comb(catalog_rows - wrong_rows, sample_rows),
        math.comb(catalog_rows, sample_rows),
    )


def format_percent(value: Fraction) -> str:
    """Round half up to one decimal place of a percent.

    The remainder test is exact. Decimal only places the rounded tenth.
    """
    if value < 0:
        raise ValueError("percent must not be negative")
    quotient, remainder = divmod(value.numerator * 1000, value.denominator)
    if remainder * 2 >= value.denominator:
        quotient += 1
    if value < 1 and quotient >= 1000:
        return ">99.9%"
    rounded = (Decimal(quotient) / Decimal(10)).quantize(
        Decimal("0.1"), rounding=ROUND_HALF_UP
    )
    return format(rounded, ".1f") + "%"


def table_block() -> str:
    """Return the fixed-width table, including its final newline."""
    header = ["N", "k", *[f"n={size}" for size in SAMPLE_SIZES]]
    rows = [header]
    for catalog_rows in CATALOG_SIZES:
        for wrong_rows in WRONG_COUNTS:
            rows.append(
                [
                    str(catalog_rows),
                    str(wrong_rows),
                    *[
                        format_percent(chance(catalog_rows, wrong_rows, sample_rows))
                        for sample_rows in SAMPLE_SIZES
                    ],
                ]
            )
    widths = [max(len(row[column]) for row in rows) for column in range(len(header))]
    lines = [
        "  ".join(cell.rjust(widths[column]) for column, cell in enumerate(row))
        for row in rows
    ]
    return "\n".join(lines) + "\n"


def _line_text(line: str) -> str:
    return line.rstrip("\r\n")


def table_parts(text: str) -> tuple[str, str, str]:
    """Return (before, body, after) for the first text fence after MARKER.

    before includes the opening fence line. after starts at the closing fence.
    """
    lines = text.splitlines(keepends=True)
    marker_at = next(
        (index for index, line in enumerate(lines) if _line_text(line) == MARKER),
        None,
    )
    if marker_at is None:
        raise TableLocationError("missing Generated by line")
    open_at = next(
        (
            index
            for index in range(marker_at + 1, len(lines))
            if _line_text(lines[index]).strip() == "```text"
        ),
        None,
    )
    if open_at is None:
        raise TableLocationError("missing text fence")
    close_at = next(
        (
            index
            for index in range(open_at + 1, len(lines))
            if _line_text(lines[index]).strip() == "```"
        ),
        None,
    )
    if close_at is None:
        raise TableLocationError("unclosed text fence")
    before = "".join(lines[: open_at + 1])
    body = "".join(lines[open_at + 1 : close_at])
    after = "".join(lines[close_at:])
    return before, body, after


def _fail(path: Path, detail: str) -> int:
    print(f"{path.name}: {detail}", file=sys.stderr)
    return 1


def check_table(path: Path) -> int:
    try:
        text = path.read_bytes().decode("utf-8")
        _before, body, _after = table_parts(text)
    except (OSError, UnicodeError, TableLocationError) as exc:
        return _fail(path, str(exc))
    if body != table_block():
        return _fail(path, "sampling table differs")
    return 0


def write_table(path: Path) -> int:
    try:
        text = path.read_bytes().decode("utf-8")
        before, _body, after = table_parts(text)
    except (OSError, UnicodeError, TableLocationError) as exc:
        return _fail(path, str(exc))
    path.write_bytes((before + table_block() + after).encode("utf-8"))
    return 0


def main(argv: list[str] | None = None, spot_checks: Path | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    path = SPOT_CHECKS if spot_checks is None else spot_checks
    if args == []:
        sys.stdout.write(table_block())
        return 0
    if args == ["--check"]:
        return check_table(path)
    if args == ["--write"]:
        return write_table(path)
    print(USAGE, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
